#!/usr/bin/env python3
"""Turns a sampling-profile run into the hot-function list used at link time (port/n64/hot_order.txt).

usage: prof_order.py <link.map> <ares output with [smp] lines> [--min N] [--budget KB] > hot_order.txt

The ROM must be built with -DN64_PROF -DN64_PROF_SAMPLE (see port/n64/prof_n64.h); its debug output has lines
"[smp] addr:count:phase ...", one entry per 32 bytes of code that was sampled. The link map gives the input section
(.text.<symbol>) of every address. Sections are grouped by the phase of the frame they ran in (present, draw, logic)
and sorted hottest first inside each group, so each phase's hot code is contiguous in the ROM.
"""
import sys, re, bisect, collections

args = [a for a in sys.argv[1:] if not a.startswith('--')]
opt = dict(zip(sys.argv[1:], sys.argv[2:]))
min_samples = int(opt.get('--min', 12))
budget = int(opt.get('--budget', 0)) * 1024
mapf, outf = args[0], args[1]

# input sections of .text from the map: name line, then "addr size file" (or all on one line for short names)
secs = []
pend = None
for line in open(mapf, encoding='utf-8', errors='replace'):
    m = re.match(r'^ (\.text\.\S+)\s*$', line)
    if m:
        pend = m.group(1)
        continue
    m = re.match(r'^ (\.text\.\S+)\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+\S', line)
    if m:
        secs.append((int(m.group(2), 16) & 0xffffffff, int(m.group(3), 16), m.group(1)))
        pend = None
        continue
    m = re.match(r'^\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+\S', line)
    if m and pend:
        secs.append((int(m.group(1), 16) & 0xffffffff, int(m.group(2), 16), pend))
    pend = None
secs = sorted(s for s in secs if s[1] > 0 and s[0] >= 0x80000000)
starts = [s[0] for s in secs]

cnt = collections.Counter()
phase = collections.defaultdict(collections.Counter)
size = {}
total = 0
for line in open(outf, encoding='utf-8', errors='replace'):
    if not line.startswith('[smp]'):
        continue
    for a, c, ph in re.findall(r'([0-9a-f]+):(\d+):(\d+)', line):
        a, c, ph = int(a, 16), int(c), int(ph)
        total += c
        i = bisect.bisect_right(starts, a + 16) - 1
        if i < 0 or a + 16 >= secs[i][0] + secs[i][1] + 32:
            continue
        name = secs[i][2]
        cnt[name] += c
        phase[name][ph] += c
        size[name] = size.get(name, 0) + 0  # filled below
for a, s, n in secs:
    if n in cnt:
        size[n] = size.get(n, 0) + s

# prof_n64.h: 0 logic, 1 draw, everything else is the present side (present, texconv, wait, audio, hash, p.*)
def group(n):
    ph = phase[n].most_common(1)[0][0]
    return 2 if ph == 0 else 1 if ph == 1 else 0

names = [n for n in cnt if cnt[n] >= min_samples]
out = []
print('# Hot code sections, in link order (tools/make_hot_ld.py). Generated by tools/prof_order.py from a profiling run:')
print('# %d samples, %d sections with >= %d samples.' % (total, len(names), min_samples))
for g, title in ((0, 'present / RDP submission / audio'), (1, 'draw: engine map and sprite rendering, gbh layer'), (2, 'game logic')):
    grp = sorted((n for n in names if group(n) == g), key=lambda n: -cnt[n])
    used = 0
    print('# ---- %s ----' % title)
    for n in grp:
        if budget and used + size[n] > budget:
            continue
        used += size[n]
        print('%s  # %d samples, %d bytes' % (n, cnt[n], size[n]))
    sys.stderr.write('%s: %d sections, %d KB, %d samples\n' % (title, len(grp), used // 1024, sum(cnt[n] for n in grp)))
